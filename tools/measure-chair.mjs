// Measures the chair in every pose and writes js/chair-table.js, so the site does not have to do it at startup.
//   node tools/measure-chair.mjs      (re-run after changing the chair's shape, poses or MINY)
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import { register } from 'node:module';
import fs from 'node:fs';
const here = path.dirname(new URL(import.meta.url).pathname);
const ctx = new Proxy({}, { get: (t, k) => (k === 'createImageData' ? (w, h) => ({ data: new Uint8ClampedArray(w * h * 4) }) : k === 'createLinearGradient' || k === 'createRadialGradient' ? () => ({ addColorStop() {} }) : () => {}), set: () => true });
globalThis.document = { createElement: () => ({ width: 0, height: 0, getContext: () => ctx, style: {} }) };
register('data:text/javascript,' + encodeURIComponent(`export async function resolve(s,c,n){if(s==='three')return{url:'file://${here}/../js/vendor/three.module.js',shortCircuit:true};if(s.startsWith('three/addons/'))return{url:'file://${here}/../js/vendor/addons/'+s.slice(13),shortCircuit:true};if(s==='./chair-table.js')return{url:'data:text/javascript,export default null;',shortCircuit:true};return n(s,c);}`), import.meta.url);
const { buildPod } = await import(pathToFileURL(path.join(here, '../js/pod.js')).href);
const pod = buildPod();
const E = pod.parts.chair.userData.table;
if (!E) throw new Error('chair.userData.table missing');
const r = (v) => +v.toFixed(3);
const out = { SL: E.SL.map(([a, b]) => [r(a), r(b)]), EXTENT: { plain: E.EXTENT.plain.map((row) => row.map(r)), ext: E.EXTENT.ext.map((row) => row.map(r)) } };
fs.writeFileSync(path.join(here, '../js/chair-table.js'), '// generated by tools/measure-chair.mjs - do not edit\nexport default ' + JSON.stringify(out) + ';\n');
console.log('wrote js/chair-table.js');
